"""Write reports/data_stats.md: class balance, lengths, review agreement.

Usage: python -m loglens.data.stats
"""

import statistics
from collections import Counter
from pathlib import Path

from loglens.data.io import read_jsonl
from loglens.data.paths import PROCESSED, REPORTS
from loglens.data.review import GOLDEN_CANDIDATES, load_reviews
from loglens.schema import CATEGORIES, SEVERITIES


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def balance_table(splits: dict[str, list[dict]], field: str, values: list[str]) -> str:
    rows = []
    for v in values:
        row = [v]
        for rows_ in splits.values():
            n = sum(r["label"][field] == v for r in rows_)
            pct = 100 * n / len(rows_) if rows_ else 0
            row.append(f"{n} ({pct:.1f}%)")
        rows.append(row)
    return _table([field, *splits.keys()], rows)


def length_table(splits: dict[str, list[dict]]) -> str:
    rows = []
    for name, rows_ in splits.items():
        lens = [len(r["message"]) for r in rows_] or [0]
        q = statistics.quantiles(lens, n=20) if len(lens) > 1 else [lens[0]] * 19
        rows.append(
            [name, len(rows_), min(lens), int(statistics.median(lens)), int(q[18]), max(lens)]
        )
    return _table(["split", "n", "min chars", "median", "p95", "max"], rows)


def review_agreement(reviews: dict[str, dict], golden_ids: set[str]) -> str:
    done = [r for i, r in reviews.items() if i in golden_ids and r["status"] != "rejected"]
    if not done:
        return "No reviewed golden items yet."
    sev = sum(r["teacher_label"]["severity"] == r["label"]["severity"] for r in done)
    cat = sum(r["teacher_label"]["category"] == r["label"]["category"] for r in done)
    status = Counter(r["status"] for i, r in reviews.items() if i in golden_ids)
    n = len(done)
    return (
        f"Reviewed golden items: {n} ({dict(status)})\n\n"
        f"- Teacher severity matched the human label: {sev}/{n} ({100 * sev / n:.1f}%)\n"
        f"- Teacher category matched the human label: {cat}/{n} ({100 * cat / n:.1f}%)"
    )


def bgl_alert_check(rows: list[dict]) -> str:
    """Loghub flags BGL alert lines; alerts labeled 'info' suggest teacher mistakes."""
    bgl = [r for r in rows if r["source"] == "bgl" and r.get("alert") is not None]
    if not bgl:
        return "No BGL rows."
    table = []
    for alert in (True, False):
        sub = [r for r in bgl if r["alert"] is alert]
        c = Counter(r["label"]["severity"] for r in sub)
        table.append(
            ["alert" if alert else "non-alert", len(sub), *[c.get(s, 0) for s in SEVERITIES]]
        )
    return _table(["BGL line", "n", *SEVERITIES], table)


def main(processed: Path = PROCESSED) -> None:
    splits = {n: list(read_jsonl(processed / f"{n}.jsonl")) for n in ("train", "val", "golden")}
    if not any(splits.values()):
        raise SystemExit("No splits found. Run: python -m loglens.data.split")
    all_rows = [r for rows in splits.values() for r in rows]
    golden_ids = {r["id"] for r in read_jsonl(GOLDEN_CANDIDATES)}
    sources = sorted({r["source"] for r in all_rows})
    by_source = [
        [s, *[sum(r["source"] == s for r in rows) for rows in splits.values()]] for s in sources
    ]
    seen = sum(r.get("seen_template", False) for r in splits["golden"])

    md = f"""# Dataset statistics

Generated by `python -m loglens.data.stats`. All counts come from the files in `data/processed/`.

## Split sizes by source

{_table(["source", *splits.keys()], by_source)}

Golden items whose template also appears in train: {seen}/{len(splits["golden"])}

## Severity balance

{balance_table(splits, "severity", SEVERITIES)}

## Category balance

{balance_table(splits, "category", CATEGORIES)}

## Message length (characters)

{length_table(splits)}

## Teacher vs human (golden set)

{review_agreement(load_reviews(), golden_ids)}

## Sanity check: BGL alert flag vs assigned severity

{bgl_alert_check(all_rows)}
"""
    REPORTS.mkdir(exist_ok=True)
    out = REPORTS / "data_stats.md"
    out.write_text(md, encoding="utf-8")
    print(md)
    print(f"written to {out}")


if __name__ == "__main__":
    main()
